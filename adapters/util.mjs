export const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

// The publisher fields every plugin manifest shares, in a stable order. `logo` and
// `license` are included only when brevo-skills.json sets them.
export function publisherFields(config) {
  const { plugin } = config;
  return {
    ...(config.logo ? { logo: config.logo } : {}),
    author: plugin.author,
    homepage: plugin.homepage,
    repository: config.repository,
    ...(config.license ? { license: config.license } : {}),
    keywords: plugin.keywords,
  };
}

// Minimal YAML writer for the small, known shapes adapters emit (maps, lists, scalars).
export function yaml(value, indent = 0) {
  const pad = ' '.repeat(indent);
  const scalar = (v) => (typeof v === 'string' && !/^[\w./:-]+$/.test(v) ? JSON.stringify(v) : String(v));
  if (Array.isArray(value)) {
    return value
      .map((item) => {
        if (item && typeof item === 'object') {
          const [first, ...rest] = yaml(item, indent + 2).split('\n').filter(Boolean);
          return [`${pad}- ${first.trimStart()}`, ...rest].join('\n');
        }
        return `${pad}- ${scalar(item)}`;
      })
      .join('\n');
  }
  return Object.entries(value)
    .map(([key, v]) => {
      if (v && typeof v === 'object') return `${pad}${key}:\n${yaml(v, indent + 2)}`;
      return `${pad}${key}: ${scalar(v)}`;
    })
    .join('\n');
}

// A skill as one self-contained Markdown text: its body, then each reference inlined.
export function inlineSkill(skill) {
  const references = Object.entries(skill.output)
    .filter(([rel]) => rel.startsWith('references/') && rel.endsWith('.md'))
    .map(([rel, content]) => `\n\n---\n\n<!-- ${rel} -->\n\n${String(content).trim()}`)
    .join('');
  return `${skill.body.trim()}${references}\n`;
}

